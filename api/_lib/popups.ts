export async function ensurePopupsSeeded(): Promise<void> {
  const countSnap = await adminDb.collection('popup_templates').count().get();
  if (countSnap.data().count >= READY_POPUP_MODELS.length) {
    return;
  }

  const existingSnap = await adminDb.collection('popup_templates').get();
  const existingCodes = new Set(existingSnap.docs.map((d) => String(d.data()?.code || '')));

  const now = new Date().toISOString();
  const batch = adminDb.batch();
  let inserted = 0;

  for (const model of READY_POPUP_MODELS) {
    if (existingCodes.has(model.code)) continue;
    const id = await nextSeqId('popup_templates');
    const docData: PopupTemplateDoc = {
      ...model,
      id,
      createdByEmail: 'system@frocrota.example',
      createdAt: now,
    };
    batch.set(adminDb.collection('popup_templates').doc(String(id)), docData);
    inserted += 1;
  }

  if (inserted > 0) {
    await batch.commit();
  }
}

export async function listActivePopups(): Promise<PopupTemplateDoc[]> {
  const today = new Date().toISOString().slice(0, 10);
  const snap = await adminDb
    .collection('popup_templates')
    .where('active', '==', true)
    .get();

  const rows = snap.docs
    .map((d) => d.data() as PopupTemplateDoc)
    .sort((a, b) => a.code.localeCompare(b.code));

  return rows
    .filter((p) => {
      const afterStart = !p.validFrom || p.validFrom <= today;
      const beforeEnd = !p.validUntil || p.validUntil >= today;
      return afterStart && beforeEnd;
    })
    .map((p) => ({ ...p, imageUrl: assetParaFotoReal(p.imageUrl) }));
}

